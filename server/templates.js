/** Короткий список для интерфейса: без содержимого, только описание. */
export const templateList = () =>
  TEMPLATES.map(({ id, title, about, goal, stages }) => ({
    id,
    title,
    about,
    goal,
    stages: stages.length,
    tasks: stages.reduce((sum, s) => sum + s.tasks.length, 0),
  }));

export const findTemplate = (id) => TEMPLATES.find((t) => t.id === id) ?? null;

/** Шаблон в вид, который понимает bulk_create: этапы с задачами и подзадачами. */
export function templateToBulk(template) {
  return {
    stages: template.stages.map((stage) => ({
      title: stage.title,
      color: stage.color,
      tasks: stage.tasks.map((task) => ({
        title: task.title,
        description: task.description ?? '',
        acceptance: task.acceptance ?? [],
        subtasks: task.subtasks ?? [],
      })),
    })),
  };
}
